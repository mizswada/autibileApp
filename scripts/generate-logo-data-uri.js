const fs = require("fs");
const path = require("path");

const logoPath = path.join(
  __dirname,
  "../assets/images/neurspatherapy_logo.png",
);
const outputPath = path.join(__dirname, "../utils/logoPdfDataUri.ts");

const buffer = fs.readFileSync(logoPath);
const base64 = buffer.toString("base64");

const contents = `// Auto-generated by scripts/generate-logo-data-uri.js — do not edit by hand.
export const LOGO_PDF_DATA_URI =
  "data:image/png;base64,${base64}";
`;

fs.writeFileSync(outputPath, contents);
console.log(
  `Wrote ${outputPath} (${buffer.length} bytes -> ${base64.length} base64 chars)`,
);
