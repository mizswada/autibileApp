const fs = require("fs");
const path = require("path");

/**
 * @deprecated PDF generation no longer uses an inline logo data URI fallback
 * (oversized base64 breaks Android release print WebViews). Logos are resized
 * at runtime via utils/getLogoBase64.ts instead. This script is kept for
 * reference only and is not required for builds.
 */
const logoPath = path.join(
  __dirname,
  "../assets/images/neurspatherapy_logo.png",
);
const outputPath = path.join(__dirname, "../utils/logoPdfDataUri.ts");

console.warn(
  "generate-logo-data-uri: deprecated — getLogoBase64() resizes the bundled asset at runtime.",
);

if (!fs.existsSync(logoPath)) {
  console.error("Logo not found:", logoPath);
  process.exit(1);
}

const buffer = fs.readFileSync(logoPath);
const base64 = buffer.toString("base64");

const contents = `// Auto-generated by scripts/generate-logo-data-uri.js — DEPRECATED, not imported by the app.
export const LOGO_PDF_DATA_URI =
  "data:image/png;base64,${base64}";
`;

fs.writeFileSync(outputPath, contents);
console.log(
  `Wrote ${outputPath} (${buffer.length} bytes -> ${base64.length} base64 chars)`,
);
